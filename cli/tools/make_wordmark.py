"""Render the wordmark once, at build time, into src/lflabs_memory_cli/banner_art.py.

The product name is set in lowercase Fredoka Bold (SIL OFL, tools/fonts/) at 22 px and drawn as braille: 2 x 4 dots a
cell, a dot wherever the glyph's grey is above 110 of 255. That gives 4 rows of 56 columns. The font never ships and
nothing renders at run time.

    uv run --group art python tools/make_wordmark.py          # rewrite banner_art.py
    uv run --group art python tools/make_wordmark.py --check  # exit 1 if banner_art.py is stale
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
from lflabs_memory_cli.brand import PRODUCT  # noqa: E402

FONT = HERE / "fonts" / "Fredoka-Bold.ttf"
OUT = HERE.parent / "src" / "lflabs_memory_cli" / "banner_art.py"
SIZE, HEIGHT, THRESH = 22, 16, 110
BITS = [[0x01, 0x08], [0x02, 0x10], [0x04, 0x20], [0x40, 0x80]]


def bitmap(text):
    """The text in a HEIGHT-pixel band, its ink centred vertically, one pixel of room on the left."""
    f = ImageFont.truetype(str(FONT), SIZE)
    left, top, right, bottom = f.getbbox(text)
    w = right - left + 2
    im = Image.new("L", (w + w % 2, HEIGHT), 0)
    ImageDraw.Draw(im).text((-left + 1, -top + (HEIGHT - (bottom - top)) // 2), text, fill=255, font=f)
    return [[1 if im.getpixel((x, y)) > THRESH else 0 for x in range(im.width)] for y in range(im.height)]


def braille(bm):
    """Braille rows, all the same width (the art is a block, so its right edge is part of the layout)."""
    h, w = len(bm), len(bm[0])
    out = []
    for r in range(0, h, 4):
        line = ""
        for c in range(0, w, 2):
            v = 0
            for dy in range(4):
                for dx in range(2):
                    if r + dy < h and c + dx < w and bm[r + dy][c + dx]:
                        v |= BITS[dy][dx]
            line += chr(0x2800 + v) if v else " "
        out.append(line)
    return out


def source():
    rows = braille(bitmap(PRODUCT.lower()))
    body = "".join(f"    {row!r},\n" for row in rows)
    return (
        '"""Generated by tools/make_wordmark.py. Do not edit by hand."""\n\n'
        f"# The wordmark: Fredoka Bold, {SIZE} px, lowercase, as braille.\n"
        f"WORDMARK = (\n{body})\n"
    )


if __name__ == "__main__":
    text = source()
    if "--check" in sys.argv[1:]:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(HERE.parent)}")
