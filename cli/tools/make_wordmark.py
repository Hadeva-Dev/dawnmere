"""Render the wordmark once, at build time, into src/lflabs_memory_cli/banner_art.py.

The product name is set in Jost (SIL OFL, tools/fonts/) at weight 550, cap height 14 px, tracking 2 px, and drawn as
braille: 2 x 4 dots a cell, a dot wherever the glyph's grey is above 110 of 255. The font never ships and nothing
renders at run time.

    uv run --group art python tools/make_wordmark.py          # rewrite banner_art.py
    uv run --group art python tools/make_wordmark.py --check  # exit 1 if banner_art.py is stale
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))
from lflabs_memory_cli.brand import PRODUCT  # noqa: E402

FONT = HERE / "fonts" / "Jost.ttf"
OUT = HERE.parent / "src" / "lflabs_memory_cli" / "banner_art.py"
CAP, WEIGHT, TRACK, THRESH = 14, 550, 2, 110
BITS = [[0x01, 0x08], [0x02, 0x10], [0x04, 0x20], [0x40, 0x80]]

# The logo for terminals without UTF-8 (spec 9.1, Fallbacks).
ASCII_LOGO = r"""      .--''''''--.
    .'            '.
   /                \
  ;      .-""-.      ;
  |    .'######'.    |
  |---'##########'---|
  ;    ~~~~~~~~~~    ;
   \      ~~~~      /
    '.            .'
      '--......--'"""


def font(size):
    f = ImageFont.truetype(str(FONT), size=size)
    f.set_variation_by_axes([WEIGHT])
    return f


def bitmap(text):
    """Rows of 0/1 pixels, CAP tall: the text with its cap height scaled to CAP pixels."""
    f = font(100)
    box = f.getbbox("H")
    f = font(round(100 * CAP / (box[3] - box[1])))
    top = f.getbbox("H")[1]
    width = sum(f.getbbox(c)[2] for c in text) + TRACK * len(text) + 8
    im = Image.new("L", (width, CAP), 0)
    draw = ImageDraw.Draw(im)
    x = 1
    for c in text:
        draw.text((x, -top), c, font=f, fill=255)
        x += f.getlength(c) + TRACK
    im = im.crop((0, 0, int(x), CAP))
    return [[1 if im.getpixel((i, j)) > THRESH else 0 for i in range(im.width)] for j in range(im.height)]


def braille(bm):
    """Braille rows, all padded to the same width (the art is a block, so its right edge is part of the layout)."""
    h, w = len(bm), len(bm[0])
    out = []
    for r in range(0, h, 4):
        line = ""
        for c in range(0, w, 2):
            v = 0
            for dy in range(4):
                for dx in range(2):
                    y, x = r + dy, c + dx
                    if y < h and x < w and bm[y][x]:
                        v |= BITS[dy][dx]
            line += chr(0x2800 + v) if v else " "
        out.append(line.rstrip())
    width = max(len(line) for line in out)
    return [line.ljust(width) for line in out]


def source():
    rows = braille(bitmap(PRODUCT.upper()))
    body = "".join(f"    {row!r},\n" for row in rows)
    logo = "".join(f"    {row!r},\n" for row in ASCII_LOGO.splitlines())
    return (
        '"""Generated by tools/make_wordmark.py. Do not edit by hand."""\n\n'
        f"# The wordmark: Jost, weight {WEIGHT}, cap {CAP} px, tracking {TRACK} px, as braille.\n"
        f"WORDMARK = (\n{body})\n\n"
        "# The logo for terminals without UTF-8.\n"
        f"ASCII_LOGO = (\n{logo})\n"
    )


if __name__ == "__main__":
    text = source()
    if "--check" in sys.argv[1:]:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(HERE.parent)}")
