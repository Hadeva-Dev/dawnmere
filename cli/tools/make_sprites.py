"""Draw Kip's sprites once, at build time, into src/lflabs_memory_cli/kip_art.py.

Kip comes from the flat drawing in tools/kip_drawing.py. Each pose is rasterised (rsvg-convert, Homebrew librsvg) and
sampled on the braille dot grid: Kip perched is 32 dots wide. A dot is on when the drawing covers at least 42% of it,
and takes the nearest of Kip's colours. The eye is a hole in the orange band, so the face survives at this size.
Nothing renders at run time.

    uv run --group art python tools/make_sprites.py          # rewrite kip_art.py
    uv run --group art python tools/make_sprites.py --check  # exit 1 if kip_art.py is stale
"""
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import kip_drawing as kip  # noqa: E402

OUT = HERE.parent / "src" / "lflabs_memory_cli" / "kip_art.py"
EYE = "#000000"
SCALE = 32 / 186            # dots per drawing unit
SS = 8                      # samples per dot, each way
COVER = 0.42
PAL = {"blue": "#3F7FE0", "wing": "#2A5BB5", "spot": "#8FC0FF", "orange": "#F25A12",
       "beak": "#3A2647", "eye": EYE, "fish": "#9C9CEB"}
LETTER = {"blue": "b", "wing": "w", "orange": "o", "beak": "k", "fish": "f"}
FEET = (110, 203)
VB = (44, 40, 186, 168)


def _rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


PALRGB = {k: _rgb(v) for k, v in PAL.items()}


def nearest(rgb):
    return min(PALRGB, key=lambda k: sum((a - b) ** 2 for a, b in zip(rgb, PALRGB[k])))


def sprite(inner, vb, anchor, tmp):
    x0, y0, w, h = vb
    W, H = round(w * SCALE), round(h * SCALE)
    src, png = Path(tmp) / "s.svg", Path(tmp) / "s.png"
    src.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0} {y0} {w} {h}">{inner}</svg>')
    subprocess.run(["rsvg-convert", "-w", str(W * SS), "-h", str(H * SS), str(src), "-o", str(png)], check=True)
    px = Image.open(png).convert("RGBA").load()
    rows = []
    for dy in range(H):
        row = ""
        for dx in range(W):
            cov, votes = 0, {}
            for sy in range(SS):
                for sx in range(SS):
                    r, g, b, a = px[dx * SS + sx, dy * SS + sy]
                    if a > 128:
                        cov += 1
                        k = nearest((r, g, b))
                        votes[k] = votes.get(k, 0) + 1
            col = max(votes, key=votes.get) if cov >= SS * SS * COVER else None
            col = "blue" if col == "spot" else col
            row += LETTER[col] if col in LETTER else "."   # the eye is a hole in the band
        rows.append(row)
    return {"ax": round((anchor[0] - x0) * SCALE), "ay": round((anchor[1] - y0) * SCALE), "rows": rows}


def _eye(s):
    return s.replace(f'<circle cx="136" cy="95" r="7.5" fill="{kip.PLUM}"/>',
                     f'<circle cx="136" cy="95" r="8.5" fill="{EYE}"/>')


def sprites():
    with tempfile.TemporaryDirectory() as tmp:
        s = {
            "perch": sprite(_eye(kip.bird()), VB, FEET, tmp),
            "blink": sprite(kip.bird(eye="shut").replace('stroke="#3A2647" stroke-width="4"',
                                                         'stroke="#F25A12" stroke-width="4"'), VB, FEET, tmp),
            "fish": sprite(_eye(kip.bird()).replace("M156 82 L226 98 L158 108", "M156 82 L222 92 L158 104")
                           + kip.fish(206, 96, 0, .95), (44, 40, 200, 168), FEET, tmp),
        }
        dive = kip.diver().replace(f'<circle cx="117" cy="134" r="6" fill="{kip.PLUM}"/>',
                                   f'<circle cx="117" cy="134" r="7" fill="{EYE}"/>')
        s["dive"] = sprite(dive, (86, 0, 70, 210), (120, 206), tmp)   # anchor: the beak tip
    return s


def source():
    out = ['"""Generated by tools/make_sprites.py. Do not edit by hand."""\n\n',
           "# Kip on the braille dot grid, one letter a dot: b blue, w wing, o orange (the mask and belly), k beak,\n",
           "# f fish, . no dot. (ax, ay) is the anchor: Kip's feet, or the beak tip for the dive.\n",
           "SPRITES = {\n"]
    for name, sp in sprites().items():
        out.append(f"    {name!r}: {{\n        'ax': {sp['ax']}, 'ay': {sp['ay']},\n        'rows': (\n")
        out += [f"            {row!r},\n" for row in sp["rows"]]
        out.append("        ),\n    },\n")
    out.append("}\n")
    return "".join(out)


if __name__ == "__main__":
    text = source()
    if "--check" in sys.argv[1:]:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(HERE.parent)}")
